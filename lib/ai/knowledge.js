export function findKnowledge(query) {
  const q = String(query || "").toLowerCase()
  return KNOWLEDGE.filter((k) => {
    const terms = k.topic.toLowerCase().split(/\s+/)
    return terms.some((t) => t.length > 3 && q.includes(t)) || q.includes(k.topic.toLowerCase())
  })
}
